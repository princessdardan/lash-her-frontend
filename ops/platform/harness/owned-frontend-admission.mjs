// Called only by the owned PostgreSQL fixture. No URL/env/remote target input.
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { randomUUID } from "node:crypto";
import { changeFrontendAdmission, observeFrontendDrain, reconcileFrontendOperation, runFrontendWriterOperation } from "../frontend-admission.mjs";

export async function exerciseFrontendAdmission(connect, password) {
  const operator = await connect("frontend_admission_owned"), runtimeRole = "frontend_admission_protocol";
  const checks = [], target = { environment: "staging", targetSha256: "a".repeat(64) };
  const producer = "b".repeat(64), source = "c".repeat(40), evidence = "d".repeat(64);
  await operator.query("CREATE ROLE frontend_admission_owner NOLOGIN NOINHERIT");
  await operator.query(`CREATE ROLE ${runtimeRole} LOGIN NOINHERIT PASSWORD '${password}'`);
  await operator.query("GRANT CREATE ON DATABASE frontend_admission_owned TO frontend_admission_owner");
  await operator.query("BEGIN");
  await operator.query("SET LOCAL ROLE frontend_admission_owner");
  await operator.query(readFileSync(new URL("../frontend-admission.sql", import.meta.url), "utf8"));
  await operator.query("INSERT INTO frontend_admission.control(environment,target_sha256) VALUES($1,$2)", [target.environment, target.targetSha256]);
  await operator.query("INSERT INTO frontend_admission.producers(producer_sha256,source_sha,database_role,enabled) VALUES($1,$2,$3::regrole::oid,true)", [producer, source, runtimeRole]);
  await operator.query(`GRANT USAGE ON SCHEMA frontend_admission TO ${runtimeRole}`);
  await operator.query(`GRANT EXECUTE ON ALL ROUTINES IN SCHEMA frontend_admission TO ${runtimeRole}`);
  await operator.query("COMMIT");
  const runtime = await connect("frontend_admission_owned", runtimeRole), historical = await connect("frontend_admission_owned", "frontend_runtime");
  const op = (epoch, kind = "new-work") => ({ id: randomUUID(), epoch, kind, producerSha256: producer, sourceSha: source });
  let effects = 0, currentEpoch = "1";
  const run = (operation, work = () => { effects++; }, client = runtime) => runFrontendWriterOperation(client, target, operation, work);
  const drain = () => observeFrontendDrain(operator, target, currentEpoch);
  const change = async (newWork, recovery) => {
    const result = await changeFrontendAdmission(operator, target, currentEpoch, { newWork, recovery }); currentEpoch = result.epoch;
  };
  await assert.rejects(run(op(currentEpoch))); assert.equal(effects, 0);
  checks.push("bootstrap-is-closed-before-any-effect");
  for (const sql of ["SELECT * FROM frontend_admission.operations", "UPDATE frontend_admission.control SET new_work=true", "DELETE FROM frontend_admission.operations", "SET ROLE frontend_admission_owner"]) await assert.rejects(runtime.query(sql));
  await change(true, true);
  const uncommitted = op(currentEpoch);
  await runtime.query("BEGIN");
  await assert.rejects(run(uncommitted));
  await runtime.query("ROLLBACK");
  assert.equal(effects, 0);
  assert.equal((await operator.query("SELECT 1 FROM frontend_admission.operations WHERE id=$1", [uncommitted.id])).rows.length, 0);
  checks.push("outer-transactions-refuse-before-effects-and-cannot-hide-uncommitted-admission");
  await assert.rejects(run(op(currentEpoch), undefined, historical));
  const active = op(currentEpoch);
  await assert.rejects(run({ ...active, sourceSha: "e".repeat(40) }));
  await assert.rejects(run({ ...active, producerSha256: "e".repeat(64) }));
  for (const mutate of [values => { values[2] = null; }, values => { values[3] = null; }, values => { values[4] = null; }, values => { values[1] = null; }]) {
    const values = [randomUUID(), "new-work", target.environment, target.targetSha256, currentEpoch, producer, source]; mutate(values);
    await assert.rejects(runtime.query("SELECT frontend_admission.admit($1,$2,$3,$4,$5,$6,$7)", values));
  }
  assert.equal(effects, 0); checks.push("historical-login-direct-table-role-spoof-and-null-bindings-refused");
  await operator.query("BEGIN"); await operator.query("SELECT singleton FROM frontend_admission.control FOR UPDATE");
  await assert.rejects(run(op(currentEpoch))); await operator.query("ROLLBACK");
  checks.push("admission-refuses-policy-lock-contention");
  let release, deferredStarted;
  const held = new Promise(resolve => { release = resolve; }), started = new Promise(resolve => { deferredStarted = resolve; });
  const pending = run(active, ({ defer }) => { effects++; defer(async () => { deferredStarted(); await held; }); });
  await started;
  await change(false, true);
  await assert.rejects(run(op(currentEpoch)));
  await run(op(currentEpoch, "recovery"));
  assert.equal((await drain()).active, 1);
  await change(false, false);
  assert.equal((await drain()).ledgerDrained, false);
  release(); await pending;
  assert.equal((await drain()).ledgerDrained, true);
  await assert.rejects(run(active));
  checks.push("new-work-stops-independently-while-recovery-and-admitted-deferred-work-finish");
  checks.push("both-controls-closed-and-zero-unresolved-required-for-ledger-drain");
  await change(true, true);
  const beforeReplay = effects;
  await assert.rejects(run({ ...active, epoch: currentEpoch }));
  assert.equal(effects, beforeReplay);
  checks.push("completed-operation-id-cannot-replay-effects");
  const uncertain = op(currentEpoch);
  await assert.rejects(run(uncertain, () => { throw new Error("private-marker"); }));
  await change(false, false);
  await operator.query("UPDATE frontend_admission.operations SET started_at='2000-01-01' WHERE id=$1", [uncertain.id]);
  assert.equal((await drain()).uncertain, 1); assert.equal((await drain()).ledgerDrained, false);
  await assert.rejects(changeFrontendAdmission(operator, target, currentEpoch, { newWork: true, recovery: false }));
  await assert.rejects(runtime.query("SELECT frontend_admission.settle($1,'completed')", [uncertain.id]));
  await assert.rejects(reconcileFrontendOperation(runtime, target, currentEpoch, uncertain.id, evidence));
  await reconcileFrontendOperation(operator, target, currentEpoch, uncertain.id, evidence);
  assert.equal((await drain()).ledgerDrained, true);
  checks.push("elapsed-time-never-drains-uncertain-work-and-only-explicit-reconciliation-clears-it");
  checks.push("unresolved-operations-refuse-restoration");
  await change(true, true);
  const abandoned = op(currentEpoch), dead = await connect("frontend_admission_owned", runtimeRole);
  dead.on("error", () => {});
  await dead.query("SELECT frontend_admission.admit($1,$2,$3,$4,$5,$6,$7)", [abandoned.id, abandoned.kind, target.environment, target.targetSha256, currentEpoch, producer, source]);
  const disconnected = new Promise(resolve => dead.once("end", resolve));
  await operator.query("SELECT pg_terminate_backend($1)", [dead.processID]); await disconnected;
  await change(false, false);
  assert.equal((await drain()).active, 1); assert.equal((await drain()).ledgerDrained, false);
  await reconcileFrontendOperation(operator, target, currentEpoch, abandoned.id, evidence);
  checks.push("actual-backend-death-retains-active-operation-until-reviewed-reconciliation");
  await change(true, true);
  const lostAdmission = op(currentEpoch), lostClient = await connect("frontend_admission_owned", runtimeRole);
  const query = lostClient.query.bind(lostClient); let calls = 0;
  lostClient.query = async (...args) => { calls++; const result = await query(...args); throw Object.assign(new Error("private-marker"), { result }); };
  const before = effects;
  await assert.rejects(run(lostAdmission, undefined, lostClient)); assert.equal(effects, before); assert.equal(calls, 1);
  await change(false, false); assert.equal((await drain()).active, 1);
  await reconcileFrontendOperation(operator, target, currentEpoch, lostAdmission.id, evidence);
  checks.push("lost-admission-acknowledgement-never-starts-effects-or-retries");
  await change(true, true);
  const lostCompletion = op(currentEpoch), completionClient = await connect("frontend_admission_owned", runtimeRole);
  const completeQuery = completionClient.query.bind(completionClient); let settles = 0;
  completionClient.query = async (sql, values) => { const result = await completeQuery(sql, values); if (sql.includes("finish_operation")) { settles++; throw new Error("private-marker"); } return result; };
  await assert.rejects(run(lostCompletion, undefined, completionClient)); assert.equal(settles, 1);
  await change(false, false); assert.equal((await drain()).ledgerDrained, true);
  checks.push("lost-completion-acknowledgement-preserves-committed-ledger-without-replay");
  await assert.rejects(changeFrontendAdmission(operator, { ...target, environment: "production" }, currentEpoch, { newWork: true, recovery: true }));
  await assert.rejects(changeFrontendAdmission(operator, target, "1", { newWork: true, recovery: true }));
  const peer = await connect("frontend_admission_owned");
  const attempts = await Promise.allSettled([operator, peer].map(client => changeFrontendAdmission(client, target, currentEpoch, { newWork: false, recovery: false })));
  assert.equal(attempts.filter(result => result.status === "fulfilled").length, 1);
  currentEpoch = attempts.find(result => result.status === "fulfilled").value.epoch;
  const observation = await drain();
  assert.equal(observation.historicalWritersFenced, false); assert.equal(observation.migrationAuthorized, false);
  checks.push("target-stale-epoch-and-concurrent-policy-changes-refuse");
  checks.push("drain-observation-never-asserts-historical-fence-or-migration-authority");
  return checks;
}
